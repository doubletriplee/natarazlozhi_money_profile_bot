def _aspect_with_ruler(facts: ChartFacts) -> tuple[str, bool, float] | None:
    ruler = facts.second_house_ruler
    if not ruler:
        return None
    candidates = []
    for aspect in facts.aspects:
        if ruler not in {aspect.first, aspect.second}:
            continue
        other = aspect.second if aspect.first == ruler else aspect.first
        candidates.append((other, aspect.harmonious, aspect.orb))
    return min(candidates, key=lambda item: item[2]) if candidates else None


def _pad(text: str, addition: str) -> str:
    if len(text) >= 500:
        return text
    return f"{text}\n\n{addition}"


