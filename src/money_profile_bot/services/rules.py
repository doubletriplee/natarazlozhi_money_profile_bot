def validate_generated_profile(profile: GeneratedProfile) -> list[str]:
    issues: list[str] = []
    banned = ("гарантирован", "точно заработ", "разбогате", "инвестируйте", "возьмите кредит")
    normalized_blocks = []
    sentence_counts: Counter[str] = Counter()
    for index, block in enumerate(profile.messages, start=1):
        lowered = block.lower()
        if not 500 <= len(block) <= 800:
            issues.append(f"message {index} length is {len(block)}, expected 500..800")
        for phrase in banned:
            if phrase in lowered:
                issues.append(f"message {index} contains banned phrase: {phrase}")
        normalized_blocks.append(" ".join(lowered.split()))
        for sentence in re.split(r"(?<=[.!?])\s+", lowered):
            normalized_sentence = " ".join(sentence.split())
            if len(normalized_sentence) >= 70:
                sentence_counts[normalized_sentence] += 1
    duplicates = [text for text, count in Counter(normalized_blocks).items() if count > 1]
    if duplicates:
        issues.append("duplicate result messages")
    if any(count > 1 for count in sentence_counts.values()):
        issues.append("duplicate long sentence across result messages")
    return issues
